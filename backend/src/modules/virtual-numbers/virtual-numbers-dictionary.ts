/**
 * مطابقة كود الخدمة واسترجاع بيانات التطبيق كاملة (الاسم العربي، الإنجليزي، الأيقونة، والأكواد)
 */
export function resolveAppMeta(
  codeOrName: string,
  providerType?: 'herosms' | 'fivesim' | string,
): {
  key: string;
  name: string;
  nameAr: string;
  nameEn: string;
  icon: string;
  herosmsCode: string;
  fivesimCode: string;
} {
  const query = normalizeKey(codeOrName);
  const provider = (providerType || '').toLowerCase();

  for (const app of VIRTUAL_NUMBER_APPS) {
    if (provider.includes('hero') && normalizeKey(app.herosmsCode) === query) {
      return {
        key: app.key,
        name: `${app.nameEn} (${app.nameAr})`,
        nameAr: app.nameAr,
        nameEn: app.nameEn,
        icon: app.icon,
        herosmsCode: app.herosmsCode,
        fivesimCode: app.fivesimCode,
      };
    }
    if (provider.includes('5sim') && normalizeKey(app.fivesimCode) === query) {
      return {
        key: app.key,
        name: `${app.nameEn} (${app.nameAr})`,
        nameAr: app.nameAr,
        nameEn: app.nameEn,
        icon: app.icon,
        herosmsCode: app.herosmsCode,
        fivesimCode: app.fivesimCode,
      };
    }
    if (
      normalizeKey(app.key) === query ||
      normalizeKey(app.herosmsCode) === query ||
      normalizeKey(app.fivesimCode) === query ||
      normalizeKey(app.nameEn) === query ||
      normalizeKey(app.nameAr) === query ||
      (app.aliases && app.aliases.some((a) => normalizeKey(a) === query))
    ) {
      return {
        key: app.key,
        name: `${app.nameEn} (${app.nameAr})`,
        nameAr: app.nameAr,
        nameEn: app.nameEn,
        icon: app.icon,
        herosmsCode: app.herosmsCode,
        fivesimCode: app.fivesimCode,
      };
    }
  }

  // إذا كانت الخدمة غير مدرجة في القاموس بعد، يبقى الاسم كما وصل من المزود
  // (الواجهات تعرض `name` حين يفرغ العربي/الإنجليزي، فلا يُعرض الرمز مكان الاسم)
  const fallback = (codeOrName || '').trim();
  return {
    key: query,
    name: fallback,
    nameAr: '',
    nameEn: '',
    icon: 'other',
    herosmsCode: fallback,
    fivesimCode: fallback,
  };
}

